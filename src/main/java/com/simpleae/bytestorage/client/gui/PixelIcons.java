    public static void draw(GuiGraphics g, String name, int x, int y, int color) {
        draw(g, name, x, y, color, 0xFFFFFFFF);
    }

    /** @param light цвет «светлых» точек ('o') */
    public static void draw(GuiGraphics g, String name, int x, int y, int color, int light) {
        String[] rows = ICONS.getOrDefault(name, ICONS.get("cube"));
        for (int r = 0; r < rows.length; r++) {
            String row = rows[r];
            for (int c = 0; c < row.length(); c++) {
                char ch = row.charAt(c);
                if (ch == '#') {
                    g.fill(x + c, y + r, x + c + 1, y + r + 1, color);
                } else if (ch == 'o') {
                    g.fill(x + c, y + r, x + c + 1, y + r + 1, light);
                }
            }
        }
    }
